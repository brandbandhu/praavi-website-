create table if not exists public.contact_leads (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null,
  phone text not null default '',
  service text not null,
  message text not null default '',
  created_at timestamptz not null default now()
);

alter table public.contact_leads enable row level security;

drop policy if exists "Public can submit contact leads" on public.contact_leads;
create policy "Public can submit contact leads"
on public.contact_leads for insert
with check (true);

drop policy if exists "Authenticated admins can read contact leads" on public.contact_leads;
create policy "Authenticated admins can read contact leads"
on public.contact_leads for select
using (auth.role() = 'authenticated');
